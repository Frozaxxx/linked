def fallback_message(*, poor_linking: bool, steps_to_target: int | None, good_depth: int, has_candidates: bool) -> str:
    if not poor_linking and steps_to_target is not None:
        return (
            f"Перелинковка хорошая: целевая страница находится за {steps_to_target} шагов "
            f"при пороге {good_depth}. Пользователь и поисковая система быстро видят ее место в структуре сайта."
        )

    candidate_note = (
        " Ниже показаны самые близкие доступные кандидаты. Среди них могут быть не только сильные тематические доноры, но и более осторожные структурные fallback-варианты."
        if has_candidates
        else " Среди разобранных страниц не найдено достаточно хороших тематических доноров."
    )
    if steps_to_target is None:
        return (
            "Перелинковка слабая: явная внутренняя дорожка от главной страницы до целевой страницы не обнаружена. "
            "Из-за этого страница может получать меньше внутреннего веса и хуже находиться в навигации."
            f"{candidate_note}"
        )
    return (
        f"Перелинковка слабая: до целевой страницы {steps_to_target} шагов, "
        f"а хороший порог для проекта - не глубже {good_depth}. "
        "Стоит добавить ссылку с действительно близкой по теме страницы, а не только из соседней ветки структуры."
        f"{candidate_note}"
    )
